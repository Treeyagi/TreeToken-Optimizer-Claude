"""Builds hooks/sprites.ts from the Treeyagi character pack.

Usage: python3 -I tools/build-sprites.py <path to Game-Character folder>
Each Clawd pose gets one Treeyagi action (front-facing row S), its frames
downscaled, cropped and embedded as small PNG data URIs.
"""
import base64, io, json, os, sys
from PIL import Image

PACK = sys.argv[1]
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'hooks', 'sprites.ts')
SIZE = 144          # frame px after downscale (from 160)
COLORS = 160

# Clawd pose -> Treeyagi action.
POSES = {
    'wake': 'stretch',
    'idle': 'idle',
    'think': 'think',
    'read': 'clearance_inspect',
    'type': 'window_sit',        # plus a laptop drawn on his lap
    'lift': 'bee_carry',
    'ask': 'wave',
    'write': 'talk',
    'compact': 'meditate',
    'done': 'victory',
    'stop': 'shrug',
    'error': 'faint',
    'cold': 'sulk',
    'sleep': 'nap',
}

char = json.load(open(os.path.join(PACK, 'treeyagi.character.json')))
anims = char['animations']
scale = 160 / SIZE
out = {}
total = 0
for pose, action in POSES.items():
    a = anims[action]
    frames = []
    for f in a['directions']['S']:
        im = Image.open(os.path.join(PACK, f['file'])).convert('RGBA').resize((SIZE, SIZE), Image.LANCZOS)
        bb = im.getchannel('A').point(lambda v: 255 if v > 8 else 0).getbbox()
        im = im.crop(bb).quantize(COLORS, method=Image.Quantize.FASTOCTREE)
        buf = io.BytesIO()
        im.save(buf, 'PNG', optimize=True)
        uri = 'data:image/png;base64,' + base64.b64encode(buf.getvalue()).decode()
        total += len(uri)
        frames.append({
            'uri': uri,
            'x': round(bb[0] * scale, 2), 'y': round(bb[1] * scale, 2),
            'w': round((bb[2] - bb[0]) * scale, 2), 'h': round((bb[3] - bb[1]) * scale, 2),
            'ms': round(f['durationMs']),
        })
    out[pose] = {'action': action, 'loop': bool(a.get('loop', True)), 'frames': frames}
    print(f'{pose:8} {action:18} {sum(len(f["uri"]) for f in frames):7} chars')

with open(OUT, 'w') as fh:
    fh.write('// Generated by tools/build-sprites.py from the Treeyagi pack. Do not edit by hand.\n')
    fh.write('export type Frame = { uri: string; x: number; y: number; w: number; h: number; ms: number }\n')
    fh.write('export type Clip = { action: string; loop: boolean; frames: Frame[] }\n')
    fh.write('export const CLIPS: Record<string, Clip> = ' + json.dumps(out) + '\n')
print('total', total, 'chars ->', OUT)
